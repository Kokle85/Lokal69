CONFIG_DIR = Path(__file__).resolve().parents[2] / "config"
AS_OF = date(2026, 10, 6)
DEFAULT = load_business_config(CONFIG_DIR)
ALL_ENABLED = load_business_config(
    CONFIG_DIR,
    overrides={"profiles": {"manual_4000": {"enabled": True}, "below_target_watch": {"enabled": True}}},
)
ELIGIBLE = {EligibilityState.ELIGIBLE_PRIMARY, EligibilityState.ELIGIBLE_MANUAL_PROFILE}


def synthetic(
    price_minor: int,
    mileage_km: Decimal,
    currency: str = "EUR",
    country: str = "DE",
    *,
    original: MileageOriginal | None = None,
    claim: OdometerClaim = OdometerClaim.SELLER_REPORTED,
    first_registration: PartialDate | None = None,
) -> NormalizedListing:
    return NormalizedListing(
        source_key="fixture_dealer_de",
        source_listing_id="SYNTH-PROP",
        canonical_url="https://dealer.example/vehicles/SYNTH-PROP",
        observed_at=datetime(2026, 10, 6, 10, 0, tzinfo=UTC),
        location=LocationInfo(country=country),
        availability=Availability.AVAILABLE,
        vehicle=VehicleSpec(
            make="Toyota",
            model="RAV4",
            body_type=BodyType.SUV,
            mileage_km=mileage_km,
            mileage_original=original or MileageOriginal(),
            mileage_claim=claim,
            first_registration=first_registration or PartialDate(),
        ),
        price=PriceInfo(
            amount_minor=price_minor,
            currency=currency,
            basis=PriceBasis.GROSS,
            type=PriceType.FULL_VEHICLE_ASKING,
            required_seller_fees_known=Tristate.NO,
        ),
        parser_version="fixture@1.0.0",
    )


def state_for(
    price_minor: int, config: BusinessConfig = DEFAULT, mileage: str = "150000"
) -> EligibilityState:
    return screen(synthetic(price_minor, Decimal(mileage)), config, [], AS_OF, default_taxonomy()).state


@settings(max_examples=150)
@given(prices=st.lists(st.integers(min_value=200_000, max_value=350_000), min_size=3, max_size=3))
def test_screening_is_monotone_in_price_within_band(prices: list[int]) -> None:
    low, mid, high = sorted(prices)
    if state_for(low) == state_for(high) == EligibilityState.ELIGIBLE_PRIMARY:
        assert state_for(mid) == EligibilityState.ELIGIBLE_PRIMARY


@settings(max_examples=150)
@given(price=st.integers(min_value=0, max_value=1_000_000))
def test_primary_band_is_exactly_2500_to_3000_inclusive(price: int) -> None:
    eligible = state_for(price) == EligibilityState.ELIGIBLE_PRIMARY
    assert eligible == (250_000 <= price <= 300_000)


