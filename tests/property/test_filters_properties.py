@settings(max_examples=200)
@given(
    year=st.integers(min_value=1990, max_value=AS_OF.year - MIN_AGE_YEARS_FOR_KM_FLOOR - 1),
    month=st.one_of(st.none(), st.integers(min_value=1, max_value=12)),
    data=st.data(),
)
def test_mileage_below_age_floor_never_eligible(year: int, month: int | None, data: st.DataObject) -> None:
    # Full years count from the last day of the registration month (31 December without a month);
    # on AS_OF (2026-10-06) an October-or-later month, or none, is therefore one year fewer.
    years = AS_OF.year - year - (1 if month is None or month >= AS_OF.month else 0)
    assert years >= MIN_AGE_YEARS_FOR_KM_FLOOR
    floor = MIN_PLAUSIBLE_KM_PER_YEAR * years
    mileage = data.draw(
        st.decimals(
            min_value=MIN_PLAUSIBLE_USED_MILEAGE_KM,
            max_value=floor - Decimal("0.001"),
            places=3,
            allow_nan=False,
        )
    )
    registration = (
        PartialDate(value=str(year), precision=Precision.YEAR)
        if month is None
        else PartialDate(value=f"{year}-{month:02d}", precision=Precision.MONTH)
    )
    listing = synthetic(275_000, mileage, first_registration=registration)
    result = screen(listing, ALL_ENABLED, [], AS_OF, default_taxonomy())
    assert result.state == EligibilityState.NEEDS_FACTS
    assert ReasonCode.MILEAGE_IMPLAUSIBLY_LOW in result.codes()
    at_floor = screen(
        synthetic(275_000, floor, first_registration=registration), ALL_ENABLED, [], AS_OF, default_taxonomy()
    )
    assert at_floor.state == EligibilityState.ELIGIBLE_PRIMARY


@settings(max_examples=200)
@given(
    year=st.integers(min_value=AS_OF.year - MIN_AGE_YEARS_FOR_KM_FLOOR, max_value=AS_OF.year),
    month=st.one_of(st.none(), st.integers(min_value=1, max_value=12)),
    mileage=st.decimals(
        min_value=MIN_PLAUSIBLE_USED_MILEAGE_KM,
        max_value=MIN_PLAUSIBLE_KM_PER_YEAR * MIN_AGE_YEARS_FOR_KM_FLOOR - Decimal("0.001"),
        places=3,
        allow_nan=False,
    ),
)
def test_age_floor_off_before_min_age(year: int, month: int | None, mileage: Decimal) -> None:
    # Under MIN_AGE_YEARS_FOR_KM_FLOOR full years only the absolute floor applies, so any reading
    # from 1,000 km up (here: up to the first age floor) stays eligible.
    years = AS_OF.year - year - (1 if month is None or month >= AS_OF.month else 0)
    assume(0 <= years < MIN_AGE_YEARS_FOR_KM_FLOOR)
    registration = (
        PartialDate(value=str(year), precision=Precision.YEAR)
        if month is None
        else PartialDate(value=f"{year}-{month:02d}", precision=Precision.MONTH)
    )
    listing = synthetic(275_000, mileage, first_registration=registration)
    result = screen(listing, ALL_ENABLED, [], AS_OF, default_taxonomy())
    assert result.state == EligibilityState.ELIGIBLE_PRIMARY
    assert ReasonCode.MILEAGE_IMPLAUSIBLY_LOW not in result.codes()


@settings(max_examples=150)
@given(
    chf_minor=st.integers(min_value=150_000, max_value=400_000),
    rate=st.decimals(min_value=Decimal("0.80"), max_value=Decimal("1.10"), places=4, allow_nan=False),
)
def test_chf_eligibility_matches_unrounded_division(chf_minor: int, rate: Decimal) -> None:
    fx = FxRate(
        base="EUR",
        quote="CHF",
        rate=rate,
        rate_date=AS_OF,
        retrieved_at=datetime(2026, 10, 6, 6, 0, tzinfo=UTC),
        provider="synthetic-test",
    )
    result = screen(
        synthetic(chf_minor, Decimal("150000"), "CHF", "CH"), DEFAULT, [fx], AS_OF, default_taxonomy()
    )
    eur = decimal.Context(prec=40).divide(Decimal(chf_minor) / 100, rate)
    assert result.eur_amount == eur
    expected = Decimal("2500") <= eur <= Decimal("3000")
    assert (result.state == EligibilityState.ELIGIBLE_PRIMARY) == expected
