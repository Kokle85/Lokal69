"""Property tests for technical-inspection wording (domain.parsing.parse_inspection).

Inputs are SYNTHETIC values generated by Hypothesis. The binding property: negated, expired or
past-dated inspection wording is never a positive roadworthy claim, whatever text surrounds it,
and seller wording is never a verified inspection.
"""

