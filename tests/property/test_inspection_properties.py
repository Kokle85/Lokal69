    "ohne HU/AU",
    "ohne gültigen TÜV",
    "kein neuer TÜV",
    "TÜV abgelaufen",
    "HU abgelaufen",
    "TÜV fällig",
    "revisione scaduta",
    "scaduta la revisione",
    "senza revisione",
