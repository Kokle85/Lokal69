@pytest.mark.parametrize("key", SOURCE_KEYS)
async def test_a_full_model_walk_reads_every_saved_model_page(key: str, client: FixtureCrawlClient) -> None:
    """Paginated search: the cursor walk over every configured model, one saved page each."""
    adapter = _adapter(key)
    request = adapter.build_search(PRIMARY, None)
    pages = []
    while True:
        page = await adapter.discover(request, client)
        pages.append(page)
        if page.access_state != AccessState.OK or not page.has_more:
            break
        request = adapter.build_search(PRIMARY, page.next_url or page.next_cursor)
    urls = model_search_urls(key)
    assert [r.url for r in client.requests] == urls and len(urls) == len(adapter.models) == 12
    assert all(r.purpose == "search" for r in client.requests)
    counts = [len(p.observations) for p in pages]
    assert counts == ([4, 2] if key == "autoscout24_it" else [3, 2]) + [0] * 10
    assert pages[1].observations[0].source_listing_id == uuid_for(201 if key == "autoscout24_it" else 601)
    assert all(p.completeness == Completeness.PARTIAL and p.has_more for p in pages[:-1])
    # Every model page was complete, so the whole walk is (absence marking may use it).
    assert pages[-1].completeness == Completeness.COMPLETE and not pages[-1].has_more
    assert "explicit empty result" in (pages[-1].access_evidence or "")


