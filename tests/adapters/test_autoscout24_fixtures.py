def client() -> FixtureCrawlClient:
    return FixtureCrawlClient([FIXTURES / key for key in SOURCE_KEYS], clock=FrozenClock(NOW))


def _adapter(key: str) -> Adapter:
    cls = AutoScout24ItAdapter if key == "autoscout24_it" else AutoScout24DeAdapter
    return cls(REGISTRY.config(key))


def _variant(key: str, case: str, path: str = "/lst/renault/captur") -> str:
    return f"https://{HOSTS[key]}{path}?fixture={case}"


async def _search(key: str, client: FixtureCrawlClient, url: str, cursor: str | None = None) -> SearchParse:
    """The adapter's `discover` over the fixture route, plus the card facts of the same page."""
    adapter = _adapter(key)
    request = SearchRequest(source_key=key, profile_key="primary", url=url, page_number=1, cursor=cursor)
    page = await adapter.discover(request, client)
    parsed = adapter.parse_search(request, await client.fetch(url, purpose="search", source_key=key))
    assert parsed.page == page  # discover() is exactly fetch + parse_search
    return parsed


async def _detail(client: FixtureCrawlClient, n: int) -> ParsedListing:
    adapter = _adapter("autoscout24_it")
    document = await adapter.fetch_detail(adapter.canonicalize(detail_url(n)), client)
    return adapter.parse_detail(document)


async def _listing(client: FixtureCrawlClient, n: int) -> NormalizedListing:
    parsed = await _detail(client, n)
    assert parsed.access_state == AccessState.OK and not parsed.errors, parsed.errors
    assert parsed.listing is not None and parsed.listing.source_listing_id == uuid_for(n)
    assert parsed.listing.parser_version == ADAPTER_VERSION
    return parsed.listing


def _screen(listing: NormalizedListing) -> Any:
    return screen(listing, BUSINESS, [], NOW.date(), TAXONOMY)


