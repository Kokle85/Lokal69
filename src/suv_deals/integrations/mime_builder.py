class InquiryMessageRef(BaseModel):
    model_config = _FROZEN

    inquiry_id: UUID
    attempt_number: int = Field(ge=1, le=MAX_ATTEMPT_NUMBER)
    domain: str


def _valid_domain(domain: str) -> bool:
    labels = domain.split(".")
    return (
        0 < len(domain) <= 253
        and len(labels) >= 2
        and all(_DOMAIN_LABEL_RE.fullmatch(label) for label in labels)
    )


def inquiry_message_id(inquiry_id: UUID, attempt_number: int, sender_domain: str) -> str:
    """``<inquiry-<uuid>.<attempt>@<sender-domain>>`` (see module docstring for semantics)."""
    if not isinstance(attempt_number, int) or not 1 <= attempt_number <= MAX_ATTEMPT_NUMBER:
        raise MimeBuildError("attempt number out of range", ["ATTEMPT_NUMBER_INVALID"])
    if not _valid_domain(sender_domain):
        raise MimeBuildError("sender domain invalid", ["SENDER_DOMAIN_INVALID"])
    return f"<inquiry-{inquiry_id}.{attempt_number}@{sender_domain}>"


def parse_inquiry_message_id(value: str | None) -> InquiryMessageRef | None:
    """Parse a Message-ID generated by this module; anything else (or a variant) is ``None``."""
    if not isinstance(value, str):
        return None
    match = _MESSAGE_ID_RE.fullmatch(value.strip())
    if match is None or not _valid_domain(match.group("domain")):
        return None
    return InquiryMessageRef(
        inquiry_id=UUID(match.group("uuid")),
        attempt_number=int(match.group("attempt")),
        domain=match.group("domain"),
    )


def inquiry_ref_value(inquiry_id: UUID) -> str:
    """Value of ``X-SUV-Inquiry-Ref``: the inquiry id only (no secret, no personal data)."""
    return f"inquiry-{inquiry_id}"


def parse_inquiry_ref(value: str | None) -> UUID | None:
    if not isinstance(value, str):
        return None
    match = _INQUIRY_REF_RE.fullmatch(value.strip())
    return UUID(match.group("uuid")) if match else None


