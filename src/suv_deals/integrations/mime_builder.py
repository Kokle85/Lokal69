def _wire_body(body: str) -> str:
    return body if body.endswith("\n") else body + "\n"


def build_message(spec: OutboundInquiryMessage) -> BuiltMessage:
    """Build and verify the RFC 5322 bytes; raises ``MimeBuildError`` with problem codes.

    The result carries no template rendering, so no provider will transmit it: seller inquiries
    are built with ``build_inquiry_message``.
    """
    return _build(spec, rendered=None)


def _build(spec: OutboundInquiryMessage, *, rendered: RenderedMessage | None) -> BuiltMessage:
    subject = unicodedata.normalize("NFC", spec.subject)
    body = unicodedata.normalize("NFC", spec.body)
    problems = header_text_problems(spec.subject, max_chars=MAX_SUBJECT_CHARS)
    problems.extend(body_text_problems(spec.body))
    if problems:
        raise MimeBuildError("message content rejected", problems)

    message_id = inquiry_message_id(spec.inquiry_id, spec.attempt_number, spec.sender.domain)
    ref = inquiry_ref_value(spec.inquiry_id)
    msg = EmailMessage(policy=_POLICY)
    try:
        msg["From"] = spec.sender.header_address()
        msg["To"] = spec.recipient.header_address()
        if spec.reply_to is not None:
            msg["Reply-To"] = spec.reply_to.header_address()
        msg["Subject"] = subject
        msg["Date"] = format_datetime(spec.date)
        msg["Message-ID"] = message_id
        msg[INQUIRY_REF_HEADER] = ref
        msg["MIME-Version"] = "1.0"
        msg.set_content(_wire_body(body), subtype="plain", charset="utf-8", cte=spec.transfer_encoding)
        raw = msg.as_bytes(policy=_POLICY)
    except (ValueError, TypeError, UnicodeError) as exc:  # library-level refusal (defence in depth)
        raise MimeBuildError("message could not be serialised safely", ["SERIALISATION_REFUSED"]) from exc
    if len(raw) > MAX_MESSAGE_BYTES:
        raise MimeBuildError("message too large", ["MESSAGE_TOO_LARGE"])
    try:
        built = BuiltMessage(
            inquiry_id=spec.inquiry_id,
            attempt_number=spec.attempt_number,
            rfc_message_id=message_id,
            inquiry_ref=ref,
            from_address=spec.sender.address,
            from_display_name=spec.sender.display_name or "",
            to_address=spec.recipient.address,
            reply_to_address=spec.reply_to.address if spec.reply_to else None,
            subject=subject,
            body=body,
            date=spec.date,
            transfer_encoding=spec.transfer_encoding,
            body_hash=message_body_hash(subject, body),
            raw=raw,
            raw_sha256=hashlib.sha256(raw).hexdigest(),
            size_bytes=len(raw),
            rendered=rendered,
        )
    except ValueError as exc:  # pydantic ValidationError: the rendering does not match the message
        raise MimeBuildError("built message is inconsistent", ["BUILT_MESSAGE_INCONSISTENT"]) from exc
    verify_built_message(built)
    return built


def build_inquiry_message(
    rendered: RenderedMessage,
    *,
    inquiry_id: UUID,
    attempt_number: int,
    sender: MailboxAddress,
    recipient_address: str,
    reply_to_address: str | None,
    date: datetime,
    transfer_encoding: TransferEncoding = "quoted-printable",
) -> BuiltMessage:
    """Build the seller inquiry from a rendered, scope-validated template.

    Refused unless the rendered message is a seller inquiry (never the informational Macedonian
    preview) that is the exact deterministic rendering of a registered template
    (``seller_templates.rendering_problems``: a hand-built or edited message is never sent, even
    when its wording stays inside the scope), the From display name is exactly the signature's
    verified sender display name, and ``seller_templates.validate_scope`` passes for the message
    *with* the real transport envelope (one recipient, no Cc/Bcc, no attachment, allowed headers
    only).
    """
    problems: list[str] = []
    if rendered.kind != "seller_inquiry":
        problems.append("NOT_A_SELLER_MESSAGE")
    else:
        problems.extend(rendering_problems(rendered))
        problems.extend(validate_scope(rendered).problems)  # the precise scope codes, if any
    if sender.display_name != rendered.placeholders.sender_display_name:
        problems.append("SENDER_DISPLAY_NAME_MISMATCH")
    if problems:
        raise MimeBuildError("rendered message cannot be sent", problems)
    spec = OutboundInquiryMessage(
        inquiry_id=inquiry_id,
        attempt_number=attempt_number,
        sender=sender,
        recipient=mailbox(recipient_address),
        reply_to=mailbox(reply_to_address) if reply_to_address is not None else None,
        subject=rendered.subject,
        body=rendered.body,
        date=date,
        transfer_encoding=transfer_encoding,
    )
    if message_body_hash(spec.subject, spec.body) != rendered.body_hash:
        raise MimeBuildError("built message differs from the rendered template", ["BODY_HASH_MISMATCH"])
    built = _build(spec, rendered=rendered)
    problems = list(inquiry_scope_problems(built))
    if problems:
        raise MimeBuildError("message is outside the bounded inquiry scope", problems)
    return built


def inquiry_scope_problems(message: BuiltMessage) -> tuple[str, ...]:
    """Why ``message`` is not a sendable bounded seller inquiry (empty = it is).

    Requires the exact registered-template rendering the message was built from, that rendering
    still being exact (``rendering_problems``), byte-for-byte the same subject/body, and
    ``validate_scope`` passing with the message's real transport envelope. Every provider calls
    this (plus ``built_message_problems``) before any I/O, so free-text or edited messages,
    previews, extra recipients, Cc/Bcc or attachments never reach a provider.
    """
    rendered = message.rendered
    if rendered is None:
        return ("NOT_A_TEMPLATE_INQUIRY",)
    problems: list[str] = []
    if rendered.kind != "seller_inquiry":
        problems.append("NOT_A_SELLER_MESSAGE")
    problems.extend(rendering_problems(rendered))
    if rendered.body_hash != message.body_hash or rendered.body_hash != message_body_hash(
        message.subject, message.body
    ):
        problems.append("BODY_HASH_MISMATCH")
    if rendered.placeholders.sender_display_name != message.from_display_name:
        problems.append("SENDER_DISPLAY_NAME_MISMATCH")
    try:
        envelope = message.envelope()
    except (KeyError, ValueError):  # tampered bytes without one of the required headers
        return tuple(sorted({*problems, "ENVELOPE_INVALID"}))
    problems.extend(validate_scope(rendered, envelope=envelope).problems)
    return tuple(sorted(set(problems)))


# =============================================================================================
# Verification of final bytes (also used by every provider immediately before submission)
# =============================================================================================


def _raw_header_block_problems(raw: bytes) -> list[str]:
    problems: list[str] = []
    head, sep, _rest = raw.partition(b"\r\n\r\n")
    if not sep:
        return ["HEADER_BLOCK_UNTERMINATED"]
    if b"\x00" in raw:
        problems.append("NUL_BYTE")
    lines = raw.split(b"\r\n")
    if any(b"\r" in line or b"\n" in line for line in lines):
        problems.append("BARE_LINE_BREAK")
    if any(len(line) > MAX_HEADER_LINE_OCTETS for line in lines):
        problems.append("LINE_TOO_LONG")
    if any(byte > 0x7F for byte in head):
        problems.append("HEADER_NOT_ASCII")
    counts: dict[str, int] = {}
    for line in head.split(b"\r\n"):
        if line[:1] in (b" ", b"\t"):
            continue  # folded continuation
        name, colon, _value = line.partition(b":")
        if not colon or not name or name != name.strip():
            problems.append("HEADER_LINE_INVALID")
            continue
        key = name.decode("ascii", "replace").lower()
        counts[key] = counts.get(key, 0) + 1
    for key, count in counts.items():
        rule = _HEADER_RULES.get(key)
        if rule is None:
            problems.append(f"HEADER_NOT_ALLOWED:{key[:40]}")
        elif count > rule[1]:
            problems.append(f"HEADER_DUPLICATED:{key}")
    for key, (required, _max) in _HEADER_RULES.items():
        if required and key not in counts:
            problems.append(f"HEADER_MISSING:{key}")
    return problems


def _single_address(parsed: EmailMessage, name: str) -> str | None:
    header = parsed[name]
    if header is None:
        return None
    groups: tuple[Any, ...] = tuple(getattr(header, "groups", ()))
    addresses: tuple[Any, ...] = tuple(getattr(header, "addresses", ()))
    if len(groups) != 1 or groups[0].display_name is not None or len(addresses) != 1:
        return None
    return str(addresses[0].addr_spec)


def built_message_problems(message: BuiltMessage) -> tuple[str, ...]:
    """Every reason the final bytes are not exactly the allowed single-recipient text message."""
    raw = message.raw
    problems = _raw_header_block_problems(raw)
    if len(raw) > MAX_MESSAGE_BYTES:
        problems.append("MESSAGE_TOO_LARGE")
    if hashlib.sha256(raw).hexdigest() != message.raw_sha256:
        problems.append("RAW_HASH_MISMATCH")
    parsed = BytesParser(policy=_PARSE_POLICY).parsebytes(raw)
    if not isinstance(parsed, EmailMessage):  # pragma: no cover - policy.default guarantees it
        return (*problems, "PARSE_FAILED")
    if parsed.defects:
        problems.append("MESSAGE_DEFECTS")
    for name in ("cc", "bcc", "resent-to", "resent-cc", "resent-bcc", "in-reply-to", "references"):
        if parsed[name] is not None:
            problems.append("FORBIDDEN_HEADER")
    if parsed.is_multipart() or parsed.get_content_type() != "text/plain":
        problems.append("NOT_SINGLE_TEXT_PART")
    if (parsed.get_content_charset() or "").lower() != "utf-8":
        problems.append("CHARSET_NOT_UTF8")
    if parsed.get_content_disposition() is not None or parsed.get_filename() is not None:
        problems.append("ATTACHMENT")
    if str(parsed.get("Content-Transfer-Encoding", "")).strip().lower() != message.transfer_encoding:
        problems.append("TRANSFER_ENCODING_MISMATCH")
    if str(parsed.get("MIME-Version", "")).strip() != "1.0":
        problems.append("MIME_VERSION_INVALID")
    to_address = _single_address(parsed, "To")
    if to_address is None:
        problems.append("RECIPIENT_COUNT")
    elif to_address != message.to_address:
        problems.append("RECIPIENT_MISMATCH")
    from_header = parsed["From"]
    from_address = _single_address(parsed, "From")
    if from_address != message.from_address:
        problems.append("SENDER_MISMATCH")
    elif from_header is not None and from_header.addresses[0].display_name != message.from_display_name:
        problems.append("SENDER_DISPLAY_NAME_MISMATCH")
    if message.reply_to_address is None:
        if parsed["Reply-To"] is not None:
            problems.append("REPLY_TO_UNEXPECTED")
    elif _single_address(parsed, "Reply-To") != message.reply_to_address:
        problems.append("REPLY_TO_MISMATCH")
    if str(parsed.get("Message-ID", "")).strip() != message.rfc_message_id:
        problems.append("MESSAGE_ID_MISMATCH")
    if parse_inquiry_ref(str(parsed.get(INQUIRY_REF_HEADER, ""))) != message.inquiry_id:
        problems.append("INQUIRY_REF_MISMATCH")
    if str(parsed.get("Subject", "")) != message.subject:
        problems.append("SUBJECT_MISMATCH")  # also catches smuggled encoded-words
    date_header = parsed["Date"]
    if date_header is None or getattr(date_header, "datetime", None) != message.date:
        problems.append("DATE_MISMATCH")
    if not problems:
        try:
            content = parsed.get_content()
        except (LookupError, ValueError, UnicodeError):
            content = None
        if not isinstance(content, str) or content.replace("\r\n", "\n") != _wire_body(message.body):
            problems.append("BODY_MISMATCH")
    return tuple(sorted(set(problems)))


def verify_built_message(message: BuiltMessage) -> None:
    """Raise ``MimeBuildError`` unless the bytes are exactly the allowed message shape."""
    problems = built_message_problems(message)
    if problems:
        raise MimeBuildError("built message failed verification", problems)


