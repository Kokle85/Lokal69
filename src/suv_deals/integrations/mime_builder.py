def header_text_problems(value: str, *, max_chars: int, allow_empty: bool = False) -> list[str]:
    """Problems of an unstructured header input (subject or display name); codes only."""
    if not isinstance(value, str):
        return ["HEADER_VALUE_INVALID"]
    problems: list[str] = []
    if any(c in _LINE_BREAKS for c in value):
        problems.append("HEADER_INJECTION")
    normalized = unicodedata.normalize("NFC", value)
    if any(unicodedata.category(c) in _FORBIDDEN_CATEGORIES for c in normalized):
        problems.append("CONTROL_CHARACTER")
    if "=?" in normalized or "?=" in normalized:
        problems.append("ENCODED_WORD_NOT_ALLOWED")
    if not normalized.strip() and not allow_empty:
        problems.append("HEADER_VALUE_EMPTY")
    if normalized != normalized.strip() or "  " in normalized:
        problems.append("HEADER_WHITESPACE")
    if len(normalized) > max_chars:
        problems.append("HEADER_VALUE_TOO_LONG")
    return problems


def display_name_problems(value: str) -> list[str]:
    problems = header_text_problems(value, max_chars=MAX_DISPLAY_NAME_CHARS)
    if any(c in _DISPLAY_SPECIALS for c in value):
        problems.append("DISPLAY_NAME_SPECIALS")
    return problems


def body_text_problems(value: str) -> list[str]:
    """The body may contain LF line breaks only; every other control/separator is refused."""
    if not isinstance(value, str):
        return ["BODY_INVALID"]
    problems: list[str] = []
    if "\r" in value or "\x85" in value or "\u2028" in value or "\u2029" in value:
        problems.append("BODY_LINE_BREAK_INVALID")
    normalized = unicodedata.normalize("NFC", value)
    if any(c != "\n" and unicodedata.category(c) in _FORBIDDEN_CATEGORIES for c in normalized):
        problems.append("CONTROL_CHARACTER")
    if not normalized.strip():
        problems.append("BODY_EMPTY")
    if len(normalized) > MAX_BODY_CHARS:
        problems.append("BODY_TOO_LONG")
    return problems


def _address_problems(raw: str) -> tuple[str | None, list[str]]:
    """Canonical address or problem codes (stricter than ``canonicalize_address`` alone)."""
    if not isinstance(raw, str):
        return None, ["ADDRESS_INVALID"]
    if any(c in _LINE_BREAKS for c in raw):
        return None, ["HEADER_INJECTION"]
    if len(raw) > MAX_ADDRESS_CHARS:
        return None, ["ADDRESS_TOO_LONG"]
    if raw != raw.strip() or any(c.isspace() for c in raw):
        return None, ["ADDRESS_INVALID"]
    if any(c in raw for c in ',;<>"()[]\\:%!'):  # second mailbox, route/% hack, group, quoting
        return None, ["ADDRESS_INVALID"]
    if any(unicodedata.category(c) in _FORBIDDEN_CATEGORIES for c in raw):
        return None, ["CONTROL_CHARACTER"]
    if raw.count("@") != 1 or not raw.split("@", 1)[0].isascii():
        return None, ["ADDRESS_INVALID"]  # no SMTPUTF8 local parts
    try:
        canonical = canonicalize_address(raw).canonical
    except AddressError as exc:
        code = "HEADER_INJECTION" if exc.problem == "HEADER_INJECTION" else "ADDRESS_INVALID"
        return None, [code]
    if len(canonical) > MAX_ADDRESS_CHARS:
        return None, ["ADDRESS_TOO_LONG"]
    return canonical, []


class MailboxAddress(BaseModel):
    """A validated mailbox: canonical address (IDNA domain) and an optional safe display name."""

    model_config = _FROZEN

    address: str = Field(max_length=MAX_ADDRESS_CHARS)
    display_name: str | None = Field(default=None, max_length=MAX_DISPLAY_NAME_CHARS)

    @field_validator("address")
    @classmethod
    def _address(cls, value: str) -> str:
        canonical, problems = _address_problems(value)
        if problems or canonical is None:
            raise ValueError("address rejected: " + ", ".join(problems))
        if canonical != value:
            raise ValueError("address must already be canonical; use mailbox()")
        return value

    @field_validator("display_name")
    @classmethod
    def _display(cls, value: str | None) -> str | None:
        if value is None:
            return None
        problems = display_name_problems(value)
        if problems:
            raise ValueError("display name rejected: " + ", ".join(sorted(set(problems))))
        if unicodedata.normalize("NFC", value) != value:
            raise ValueError("display name must be NFC; use mailbox()")
        return value

    @property
    def local_part(self) -> str:
        return self.address.split("@", 1)[0]

    @property
    def domain(self) -> str:
        return self.address.split("@", 1)[1]

    def header_address(self) -> Address:
        return Address(display_name=self.display_name or "", username=self.local_part, domain=self.domain)


def mailbox(address: str, display_name: str | None = None) -> MailboxAddress:
    """Validate and canonicalise; raises ``MimeBuildError`` with problem codes."""
    canonical, problems = _address_problems(address)
    name: str | None = None
    if display_name is not None:
        problems.extend(display_name_problems(display_name))
        name = unicodedata.normalize("NFC", display_name)
    if problems or canonical is None:
        raise MimeBuildError("mailbox rejected", problems)
    return MailboxAddress(address=canonical, display_name=name)


