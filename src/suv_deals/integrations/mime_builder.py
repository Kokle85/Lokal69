"""RFC 5322 / MIME builder for the bounded seller inquiry (spec 37.1, 37.3, 37.5).

One message shape only: a single ``text/plain; charset="utf-8"`` part (quoted-printable or
base64 body), built with Python's ``email`` package (``EmailMessage`` + ``policy.SMTP``), with
exactly these headers and nothing else::

    From: <verified display name> <verified sender address>
    To: <exactly one verified seller address>          (no display name: seller text never
                                                        enters a header)
    Reply-To: <verified alias>                          (optional)
    Subject: <rendered template subject>               (RFC 2047 encoded when non-ASCII)
    Date: <RFC 5322 date, UTC>
    Message-ID: <inquiry-<uuid>.<attempt>@<sender-domain>>
    X-SUV-Inquiry-Ref: inquiry-<uuid>                  (the inquiry id only; never a secret)
    MIME-Version: 1.0
    Content-Type: text/plain; charset="utf-8"
    Content-Transfer-Encoding: quoted-printable | base64

There is no Cc, Bcc, Resent-*, In-Reply-To/References (an initial inquiry is never a reply or a
follow-up), no multipart container and no attachment: the API offers no way to add them, and
``verify_built_message`` re-parses the final bytes and refuses anything else.

Header-injection defence (defence in depth, all mandatory):

1. Every header input is NFC-normalised and rejected when it contains CR, LF, NUL, any other
   control character, U+0085/U+2028/U+2029 line separators, Unicode format characters (bidi
   overrides, zero-width), surrogates, private-use or unassigned code points, RFC 2047
   encoded-word markers (``=?``/``?=``) or exceeds its length bound.
2. Addresses use a conservative RFC 5321/5322 subset (``seller_contacts.canonicalize_address``):
   dot-atom local part of common characters only (no quoted strings, comments, group syntax,
   route addresses, ``%`` source-route hacks or SMTPUTF8 local parts), IDNA-encoded lower-case
   domain, total <= 254. Commas, semicolons, angle brackets or whitespace (a second recipient)
   are rejected.
3. Display names reject RFC 5322 specials (``<>@,;:"\\[]()``) so an attacker-shaped name can
   never smuggle an address, and are RFC 2047 encoded by the library when non-ASCII.
4. The generated bytes are parsed again and checked: header allow-list with exact counts,
   CRLF-only line endings, physical lines <= 998 octets, folded continuation lines, exactly one
   To mailbox (no groups), no defects, single non-multipart ``text/plain`` UTF-8 part, and the
   decoded subject/body/addresses equal the inputs exactly (an encoded-word smuggled into the
   subject would decode differently and is refused).

Bounded scope: ``build_inquiry_message`` accepts only the exact deterministic rendering of a
registered seller template (``seller_templates.rendering_problems``) whose scope validates with the
real transport envelope, and stores that rendering on the ``BuiltMessage``. ``inquiry_scope_problems``
re-checks it, and every provider runs it before any I/O: a message assembled any other way (for
example with ``build_message`` from free text) is never transmitted.

Determinism: the same ``OutboundInquiryMessage`` always yields the same bytes (explicit
``Date``, no random MIME boundary because there is a single part, fixed header order), so
``raw_sha256`` identifies the exact transmitted request. A Python upgrade could in principle
change header folding; the hash is therefore recorded per attempt, never recomputed later.

Message-ID: ``<inquiry-<inquiry uuid>.<attempt number>@<sender domain>>``, stable for one
attempt (rebuilding the same attempt yields the same Message-ID and bytes) and different for
each new attempt so reconciliation evidence is attributable to an attempt. Reusing a Message-ID
is NOT a universal server-side de-duplication guarantee: providers may rewrite it (Gmail and
Exchange may assign their own), may accept the same Message-ID twice, and Outlook ``.Send`` may
ignore a client value. The value is a correlation and search key only; an uncertain send is
never retried on the assumption that a provider will drop the duplicate.
"""

