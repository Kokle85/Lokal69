MIME_BUILDER_VERSION: Final = "mime-builder/1"
MAX_DISPLAY_NAME_CHARS: Final = 64
MAX_SUBJECT_CHARS: Final = 200
MAX_BODY_CHARS: Final = 4_000
MAX_ADDRESS_CHARS: Final = 254
MAX_MESSAGE_BYTES: Final = 64 * 1024
MAX_HEADER_LINE_OCTETS: Final = 998  # RFC 5322 section 2.1.1 hard limit (excluding CRLF)
FOLD_LINE_LENGTH: Final = 78  # RFC 5322 recommended limit used for folding
MAX_ATTEMPT_NUMBER: Final = 99
INQUIRY_REF_HEADER: Final = "X-SUV-Inquiry-Ref"
CONTENT_TYPE_VALUE: Final = 'text/plain; charset="utf-8"'

TransferEncoding = Literal["quoted-printable", "base64"]

_FROZEN = ConfigDict(frozen=True, extra="forbid")
_POLICY: Final = policy.SMTP.clone(max_line_length=FOLD_LINE_LENGTH)
_PARSE_POLICY: Final = policy.default

#: Header name -> (required, maximum count). Nothing outside this map may appear.
_HEADER_RULES: Final[dict[str, tuple[bool, int]]] = {
    "from": (True, 1),
    "to": (True, 1),
    "reply-to": (False, 1),
    "subject": (True, 1),
    "date": (True, 1),
    "message-id": (True, 1),
    INQUIRY_REF_HEADER.lower(): (True, 1),
    "mime-version": (True, 1),
    "content-type": (True, 1),
    "content-transfer-encoding": (True, 1),
}
_HEADER_ORDER: Final = (
    "From",
    "To",
    "Reply-To",
    "Subject",
    "Date",
    "Message-ID",
    INQUIRY_REF_HEADER,
    "MIME-Version",
    "Content-Type",
    "Content-Transfer-Encoding",
)
#: Characters that are never acceptable in any header input (checked before normalisation too).
_LINE_BREAKS: Final = frozenset("\r\n\x00\x0b\x0c\x1c\x1d\x1e\x85\u2028\u2029")
_FORBIDDEN_CATEGORIES: Final = frozenset({"Cc", "Cf", "Co", "Cs", "Cn", "Zl", "Zp"})
_DISPLAY_SPECIALS: Final = frozenset('<>@,;:"\\[]()')
_UUID_TEXT: Final = r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"
_MESSAGE_ID_RE: Final = re.compile(
    rf"^<inquiry-(?P<uuid>{_UUID_TEXT})\.(?P<attempt>[1-9][0-9]?)@(?P<domain>[a-z0-9.-]{{1,253}})>$"
)
_INQUIRY_REF_RE: Final = re.compile(rf"^inquiry-(?P<uuid>{_UUID_TEXT})$")
_DOMAIN_LABEL_RE: Final = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$")


class MimeBuildError(ValidationFailed):
    """The message (or one of its inputs) is refused; ``problems`` are stable codes."""

    def __init__(self, message: str, problems: list[str] | tuple[str, ...]) -> None:
        self.problems: tuple[str, ...] = tuple(sorted(set(problems)))
        super().__init__(message, details={"problems": list(self.problems)})


