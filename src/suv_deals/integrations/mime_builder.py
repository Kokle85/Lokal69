class OutboundInquiryMessage(BaseModel):
    """Everything that goes into the message. There are deliberately no cc/bcc/attachment fields."""

    model_config = _FROZEN

    inquiry_id: UUID
    attempt_number: int = Field(ge=1, le=MAX_ATTEMPT_NUMBER)
    sender: MailboxAddress
    recipient: MailboxAddress
    reply_to: MailboxAddress | None = None
    subject: str = Field(max_length=MAX_SUBJECT_CHARS * 2)
    body: str = Field(max_length=MAX_BODY_CHARS * 2)
    date: datetime
    transfer_encoding: TransferEncoding = "quoted-printable"

    @field_validator("date")
    @classmethod
    def _date(cls, value: datetime) -> datetime:
        return ensure_utc(value).replace(microsecond=0)

    @model_validator(mode="after")
    def _roles(self) -> OutboundInquiryMessage:
        if not self.sender.display_name:
            raise ValueError("the verified sender display name is required")
        if self.recipient.display_name is not None:
            raise ValueError("the recipient carries no display name (seller text never enters headers)")
        if self.reply_to is not None and self.reply_to.display_name is not None:
            raise ValueError("Reply-To carries no display name")
        if self.recipient.address.casefold() == self.sender.address.casefold():
            raise ValueError("recipient must not be the sender")
        if (
            self.reply_to is not None
            and self.reply_to.address.casefold() == self.recipient.address.casefold()
        ):
            raise ValueError("Reply-To must be the sender's verified alias, never the recipient")
        return self


class BuiltMessage(BaseModel):
    """The exact bytes to submit plus the metadata the attempt record stores."""

    model_config = _FROZEN

    builder_version: str = MIME_BUILDER_VERSION
    inquiry_id: UUID
    attempt_number: int = Field(ge=1, le=MAX_ATTEMPT_NUMBER)
    rfc_message_id: str
    inquiry_ref: str
    from_address: str
    from_display_name: str
    to_address: str
    reply_to_address: str | None
    subject: str
    body: str
    date: datetime
    transfer_encoding: TransferEncoding
    body_hash: str
    raw: bytes = Field(max_length=MAX_MESSAGE_BYTES)
    raw_sha256: str
    size_bytes: int = Field(ge=1, le=MAX_MESSAGE_BYTES)
    #: The exact registered-template rendering this message was built from (set only by
    #: ``build_inquiry_message``). ``None`` means "not a seller inquiry": providers refuse it.
    rendered: RenderedMessage | None = None

    @model_validator(mode="after")
    def _consistent(self) -> BuiltMessage:
        if hashlib.sha256(self.raw).hexdigest() != self.raw_sha256 or len(self.raw) != self.size_bytes:
            raise ValueError("raw bytes do not match their hash/size")
        if self.rendered is not None and (
            self.rendered.kind != "seller_inquiry"
            or self.rendered.body_hash != self.body_hash
            or self.rendered.placeholders.sender_display_name != self.from_display_name
        ):
            raise ValueError("the rendered template does not match the built message")
        if parse_inquiry_message_id(self.rfc_message_id) != InquiryMessageRef(
            inquiry_id=self.inquiry_id,
            attempt_number=self.attempt_number,
            domain=self.from_address.split("@", 1)[-1],
        ):
            raise ValueError("Message-ID does not match inquiry, attempt and sender domain")
        if self.inquiry_ref != inquiry_ref_value(self.inquiry_id):
            raise ValueError("inquiry reference does not match the inquiry id")
        if self.body_hash != message_body_hash(self.subject, self.body):
            raise ValueError("body hash does not match subject and body")
        return self

    @property
    def sender_domain(self) -> str:
        return self.from_address.split("@", 1)[1]

    def raw_base64url(self) -> str:
        """URL-safe base64 of the RFC 2822 bytes (Gmail ``users.messages.send`` ``raw``)."""
        return base64.urlsafe_b64encode(self.raw).decode("ascii")

    def raw_base64(self) -> str:
        """Standard base64 of the MIME bytes (Microsoft Graph ``sendMail`` MIME body)."""
        return base64.b64encode(self.raw).decode("ascii")

    def header_values(self) -> dict[str, str]:
        """The structured header values as serialised (unfolded), for scope validation/audit."""
        parsed = BytesParser(policy=_PARSE_POLICY).parsebytes(self.raw)
        return {
            name: " ".join(str(parsed[name]).split()) for name in _HEADER_ORDER if parsed[name] is not None
        }

    def envelope(self) -> MessageEnvelope:
        """Transport envelope for ``seller_templates.validate_scope``: every extra header of the
        final bytes, including the technical ``X-SUV-Inquiry-Ref`` correlation header (allow-listed
        by ``seller_templates`` with the exact value shape ``inquiry-<lower-case uuid>``)."""
        values = self.header_values()
        extra = {
            name: values[name]
            for name in (
                "Message-ID",
                "Date",
                INQUIRY_REF_HEADER,
                "MIME-Version",
                "Content-Type",
                "Content-Transfer-Encoding",
            )
        }
        return MessageEnvelope(
            to=(self.to_address,),
            reply_to=(self.reply_to_address,) if self.reply_to_address else (),
            extra_headers=extra,
        )


